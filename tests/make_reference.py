# 3. Synthetic clustered data for the instrumented side.
#    tests/synthetic_iv.csv holds three small designs drawn with a fixed seed;
#    their reference values are computed below by an independent NumPy
#    implementation (residualise on the controls, weighted-free slopes,
#    per-cluster influence-function sums without a small-sample factor, the
#    Fieller quadratic), not by toolkit/prelevel_dose.py.  The designs are
#    chosen so that the Fieller set of g_IV/beta_IV takes each of its three
#    shapes.  Stata reads the CSV and runs preleveldose_ols ..., iv(z), and the
#    moment route through preleveldose_iv and preleveldose.
SYN_CSV = ROOT / 'tests' / 'synthetic_iv.csv'
SYN_COLS = ['design', 'cluster', 'baseline', 'dose', 'change', 'c1', 'c2', 'z']
Z95 = NormalDist().inv_cdf(0.975)


def ind_fieller(N, D, vN, vD, c, z=Z95):
    a = D * D - z * z * vD
    bq = -2.0 * (N * D - z * z * c)
    cc = N * N - z * z * vN
    disc = bq * bq - 4.0 * a * cc
    if a > 0:
        r = math.sqrt(max(disc, 0.0))
        return 'bounded', (-bq - r) / (2 * a), (-bq + r) / (2 * a), a, disc
    if a < 0 and disc > 0:
        r1, r2 = sorted([(-bq - math.sqrt(disc)) / (2 * a), (-bq + math.sqrt(disc)) / (2 * a)])
        return 'two_rays', r1, r2, a, disc
    return 'whole_line', None, None, a, disc


def ind_set(prefix, N, D, vN, vD, c):
    shape, lo, hi, _, _ = ind_fieller(N, D, vN, vD, c)
    return {f'{prefix}_shape': shape, f'{prefix}_lo': lo, f'{prefix}_hi': hi}


def ind_design(X):
    """Independent NumPy reference for one design of synthetic_iv.csv."""
    cl, S0, H0, D0, c1, c2, Z0 = (X[:, j] for j in range(7))
    C = np.column_stack([np.ones(len(S0)), c1, c2])

    def res(v):
        co, *_ = np.linalg.lstsq(C, v, rcond=None)
        return v - C @ co
    S, H, D, Z = res(S0), res(H0), res(D0), res(Z0)
    codes = np.unique(cl, return_inverse=True)[1]
    G = codes.max() + 1

    def slope(y, x):
        sxx = float(x @ x)
        th = float(x @ y) / sxx
        return th, np.bincount(codes, weights=x * (y - th * x) / sxx, minlength=G)
    beta, p_beta = slope(D, H)
    gr, p_gr = slope(D, S)
    bn, p_bn = slope(H, S)
    g, p_g = slope(S, H)
    b = -bn
    P = np.column_stack([p_beta, p_gr, -p_bn, p_g])
    V = P.T @ P                                         # (beta, rho, b, g)
    se_beta, se_g = math.sqrt(V[0, 0]), math.sqrt(V[3, 3])
    corrgb = V[3, 0] / (se_g * se_beta)
    rho = 1.0 + gr
    R2 = min(1.0, (b * S.std() / H.std()) ** 2)
    full, *_ = np.linalg.lstsq(np.column_stack([C, H0, S0]), D0, rcond=None)
    pS, q_S = slope(S, Z)
    pH, q_H = slope(H, Z)
    pD, q_D = slope(D, Z)
    Q4 = np.column_stack([p_gr, q_S, q_H, q_D])
    W = Q4.T @ Q4                                       # (rho, pS, pH, pD)
    gs = ind_set('gb', g, beta, V[3, 3], V[0, 0], V[3, 0])
    sh, lo, hi = gs['gb_shape'], gs['gb_lo'], gs['gb_hi']
    if sh == 'bounded':
        mag = (0.0, max(abs(lo), abs(hi))) if lo <= 0 <= hi else (min(abs(lo), abs(hi)), max(abs(lo), abs(hi)))
    elif sh == 'two_rays' and lo < 0 < hi:
        mag = (min(-lo, hi), None)
    else:
        mag = (0.0, None)
    ols = {'beta': beta, 'rho_obs': rho, 'b': b, 'R2': R2, 'g': g,
           'bound_ratio': abs(g) / abs(beta), 'gb_ratio': g / beta, **gs,
           'bound_ratio_lo': mag[0], 'bound_ratio_hi': mag[1],
           'rho_imp': 1.0 + full[4], 'one_plus_gamma': 1.0 + full[4]}
    g_iv, b_iv = pS / pH, pD / pH
    iv = {'g_iv': g_iv, 'beta_iv': b_iv, 'giv_ratio': pS / pD, 'Q': (rho - 1) * pS / pD,
          'channel_iv': (rho - 1) * g_iv, 'bound_iv': abs(g_iv),
          'bound_ratio_iv': abs(g_iv) / abs(b_iv)}
    iv.update(ind_set('giv', pS, pH, W[1, 1], W[2, 2], W[1, 2]))
    iv.update(ind_set('givb', pS, pD, W[1, 1], W[3, 3], W[1, 3]))
    gq = np.array([pS, rho - 1.0, 0.0, 0.0])
    iv.update(ind_set('Q', (rho - 1) * pS, pD, float(gq @ W @ gq), W[3, 3], float(gq @ W[:, 3])))
    mom = dict(rho=rho, czs=pS, czh=pH, czy=pD, V=W.tolist(), beta=beta, b=b, r2=R2,
               seg=se_g, sebeta=se_beta, corrgb=corrgb)
    # margin of the g_IV/beta_IV quadratic: a, discriminant, and its scale
    zz = Z95 * Z95
    a = pD * pD - zz * W[3, 3]
    bq = -2.0 * (pS * pD - zz * W[1, 3])
    cc = pS * pS - zz * W[1, 1]
    return ols, iv, mom, (a, bq * bq - 4 * a * cc, bq * bq + abs(4 * a * cc))


def draw(seed, n_clusters, per, pi_h, pi_s, beta, rho, noise):
    r = np.random.default_rng(seed)
    cl = np.repeat(np.arange(1, n_clusters + 1), per).astype(float)
    u = r.normal(0, 1, n_clusters)[cl.astype(int) - 1]
    c1 = r.normal(0, 1, cl.size)
    c2 = (cl % 3 == 0).astype(float)
    S = 0.5 * u + 0.3 * c1 + r.normal(0, 1, cl.size)
    v = r.normal(0, 1, cl.size)
    H = -0.5 * S + v + 0.2 * c2
    Z = pi_h * v + pi_s * S + r.normal(0, 1, cl.size)
    D = beta * H + (rho - 1.0) * S + 0.1 * c1 + noise * (0.5 * u + r.normal(0, 1, cl.size))
    return np.column_stack([cl, S, H, D, c1, c2, Z])


