def g17(v):
    return f'{v:.17g}'


def num(v):
    """JSON-safe number: infinities and NaN (Stata missing) become None."""
    if v is None:
        return None
    v = float(v)
    return v if math.isfinite(v) else None


def fset(prefix, f):
    return {f'{prefix}_shape': f.shape, f'{prefix}_lo': num(f.lo),
            f'{prefix}_hi': num(f.hi)}


def assert_lines(expected, tol='1e-9'):
    out = []
    for key, value in expected.items():
        if isinstance(value, str):
            out.append(f'assert "`r({key})\'" == "{value}"')
        elif value is None:
            out.append(f'assert missing(r({key}))')
        else:
            out.append(f'assert reldif(r({key}), {g17(value)}) < {tol}')
    return out


